window.openTikTokModal = function(id) {
  const item = (CURRENT_TIKTOK_DATA && CURRENT_TIKTOK_DATA.length ? CURRENT_TIKTOK_DATA : TIKTOK_DATA).find(t => t.id === id);
  if (!item) return;

  activeTikTokVideo = item;
  const modal = document.getElementById('tiktok-modal');
  const titleEl = document.getElementById('tiktok-modal-title');
  const bodyEl = document.getElementById('tiktok-modal-body');
  const linkEl = document.getElementById('tiktok-modal-link');

  if (titleEl) {
    titleEl.innerHTML = `
      <svg width="18" height="18" viewBox="0 0 24 24" fill="#00f2fe"><path d="M19.59 6.69a4.83 4.83 0 0 1-3.77-4.25V2h-3.45v13.67a2.89 2.89 0 0 1-5.2 1.74 2.89 2.89 0 0 1 2.31-4.64 2.93 2.93 0 0 1 .88.13V9.4a6.84 6.84 0 0 0-1-.05A6.33 6.33 0 0 0 3 15.68 6.34 6.34 0 0 0 9.35 22a6.33 6.33 0 0 0 6.32-6.32V8.92a8.28 8.28 0 0 0 4.84 1.57v-3.8z"/></svg>
      <span>${item.title}</span>
    `;
  }
  if (linkEl) linkEl.href = item.url;

  if (bodyEl) {
    bodyEl.innerHTML = `
      <div style="width: 100%; height: 100%; display: flex; align-items: center; justify-content: center; background: #000; position: relative;">
        <video id="active-tiktok-video" 
               controls 
               playsinline 
               preload="auto" 
               poster="${item.thumb}" 
               style="width: 100%; height: 100%; max-height: 560px; object-fit: contain; outline: none; background: #000;">
          <source src="${item.videoSrc}" type="video/mp4">
          عذراً، متصفحك لا يدعم تشغيل هذا المقطع مباشرة.
        </video>
        <button id="tiktok-play-center-btn" style="position: absolute; width: 68px; height: 68px; border-radius: 50%; background: linear-gradient(135deg, #00f2fe, #fe2c55); border: none; color: #fff; font-size: 1.8rem; display: flex; align-items: center; justify-content: center; cursor: pointer; box-shadow: 0 0 25px rgba(254,44,85,0.7); z-index: 4; transition: transform 0.2s ease;">
          ▶
        </button>
        <div id="tiktok-unmute-notice" style="display: none; position: absolute; top: 14px; left: 50%; transform: translateX(-50%); background: rgba(0,0,0,0.85); backdrop-filter: blur(8px); color: #00f2fe; border: 1px solid rgba(0,242,254,0.5); padding: 6px 16px; border-radius: 20px; font-size: 0.82rem; cursor: pointer; z-index: 6; box-shadow: 0 4px 15px rgba(0,0,0,0.6);">
          🔊 انقر لتشغيل الصوت
        </div>
      </div>
    `;
  }

  if (modal) {
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
  }

  // Play video logic
  setTimeout(() => {
    const vid = document.getElementById('active-tiktok-video');
    const playBtn = document.getElementById('tiktok-play-center-btn');
    const unmuteBanner = document.getElementById('tiktok-unmute-notice');
    if (!vid) return;

    function triggerPlay() {
      const p = vid.play();
      if (p !== undefined) {
        p.then(() => {
          if (playBtn) playBtn.style.display = 'none';
        }).catch(() => {
          // Fallback: browser requires muted autoplay
          vid.muted = true;
          vid.play().then(() => {
            if (playBtn) playBtn.style.display = 'none';
            if (unmuteBanner) {
              unmuteBanner.style.display = 'block';
              unmuteBanner.onclick = () => {
                vid.muted = false;
                unmuteBanner.style.display = 'none';
              };
            }
          }).catch(() => {
            if (playBtn) playBtn.style.display = 'flex';
          });
        });
      }
    }

    if (playBtn) {
      playBtn.onclick = () => {
        vid.muted = false;
        triggerPlay();
      };
    }

    vid.addEventListener('play', () => {
      if (playBtn) playBtn.style.display = 'none';
    });
    vid.addEventListener('pause', () => {
      if (playBtn && !vid.seeking) playBtn.style.display = 'flex';
    });

    triggerPlay();
  }, 100);
};

function initTikTokModalEvents() {
  const modal = document.getElementById('tiktok-modal');
  const closeBtn = document.getElementById('close-tiktok-modal-btn');

  function closeTikTokModal() {
    if (!modal) return;
    const activeVid = document.getElementById('active-tiktok-video');
    if (activeVid) {
      activeVid.pause();
    }
    const bodyEl = document.getElementById('tiktok-modal-body');
    if (bodyEl) {
      bodyEl.innerHTML = '';
    }
    modal.classList.remove('active');
    document.body.style.overflow = '';
  }

  if (closeBtn) closeBtn.addEventListener('click', closeTikTokModal);
  if (modal) {
    modal.addEventListener('click', e => {
      if (e.target === modal) closeTikTokModal();
    });
  }

  document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && modal && modal.classList.contains('active')) {
      closeTikTokModal();
    }
  });
}


